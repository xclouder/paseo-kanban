import { homedir } from 'node:os';
import { logOperation } from './operation-log';
import { join } from 'node:path';
import type { PluginHandlerContext } from '@getpaseo/plugin/server';
import { BoardService } from './service';
import { Store } from './store';
import type { ProjectAction } from '../shared/projects';
import type { AddInboxInput, CompleteReviewInput, CreateInput, CreateProjectWorkspaceInput, HideDoneInput, LaunchInput, MoveInput, PatchInboxInput, PatchInput } from '../shared/contracts';
import type { KanbanSettingsPatch } from '../shared/settings';

const service = new BoardService(new Store(join(process.env.PASEO_HOME || join(homedir(), '.paseo'), 'paseo-kanban', 'board.json')));
export const read = logOperation('read', (_: object, { paseo }: PluginHandlerContext) => service.read(paseo));
export const readSettings = logOperation('readSettings', () => service.readSettings());
export const saveSettings = logOperation('saveSettings', (input: KanbanSettingsPatch) => service.saveSettings(input));
export const organize = logOperation('organize', (input: ProjectAction, { paseo }: PluginHandlerContext) => service.organizeProjects(input, paseo));
export const patch = logOperation('patch', (input: PatchInput, { paseo }: PluginHandlerContext) => service.patch(input, paseo));
export const move = logOperation('move', (input: MoveInput, { paseo }: PluginHandlerContext) => service.move(input, paseo));
export const completeReview = logOperation('completeReview', (input: CompleteReviewInput, { paseo }: PluginHandlerContext) => service.completeReview(input, paseo));
export const hideDone = logOperation('hideDone', (input: HideDoneInput, { paseo }: PluginHandlerContext) => service.hideDone(input, paseo));
export const addInbox = logOperation('addInbox', (input: AddInboxInput) => service.addInbox(input));
export const patchInbox = logOperation('patchInbox', (input: PatchInboxInput) => service.patchInbox(input));
export const deleteInbox = logOperation('deleteInbox', ({ id }: { id: string }) => service.deleteInbox(id));
export const create = logOperation('create', (input: CreateInput, { paseo }: PluginHandlerContext) => service.create(input, paseo));
export const createProjectWorkspace = logOperation('createProjectWorkspace', (input: CreateProjectWorkspaceInput, { paseo }: PluginHandlerContext) => service.createProjectWorkspace(input, paseo));
export const launch = logOperation('launch', ({ id, confirmedWorkspaceId }: LaunchInput, { paseo }: PluginHandlerContext) => service.launch(id, paseo, confirmedWorkspaceId));
export const remove = logOperation('remove', ({ id }: { id: string }) => service.delete(id));
